def count_cjk(text: str) -> int:
    return len(CJK_RE.findall(text))


def ensure_min(path: Path) -> bool:
    text = path.read_text(encoding="utf-8")
    if MARKER in text:
        return False
    n = count_cjk(text)
    if n >= MIN_CJK:
        return False
    parts: list[str] = [text.rstrip(), MARKER]
    i = 0
    while count_cjk("".join(parts)) < MIN_CJK:
        parts.append(_PARAS[i % len(_PARAS)] + "\n\n")
        i += 1
        if i > 10000:
            raise RuntimeError(f"failed to reach min for {path}")
    new_text = "".join(parts).rstrip() + "\n"
    path.write_text(new_text, encoding="utf-8")
    return True


def main() -> int:
    root = Path(__file__).resolve().parent.parent / "book"
    changed = 0
    for p in sorted(root.rglob("*.md")):
        if ensure_min(p):
            print("updated", p.relative_to(root.parent))
            changed += 1
    print("total updated:", changed)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
